def chute_img():
    w, h = 24, 40; img = blank(w, h)
    for y in range(h):
        for x in range(w):
            if y < 2: c = 2
            elif y < 8: c = 1 if (x < 2 or x >= w - 2) else 3
            elif y < 10: c = 2
            else:
                c = 1
                if x == 0 or x == w - 1 or y >= h - 2: c = 2
            img[y][x] = c
    # down arrow on the face
    for y in range(14, 34):
        for x in range(w):
            dx = abs(x + .5 - 12)
            if y < 24 and dx <= 2.5: img[y][x] = 2
            if 24 <= y < 34 and dx <= (33 - y) * 0.8: img[y][x] = 2
    return img

def pile_img(w=120, seed=7):
    rnd = random.Random(seed); img = blank(w, 8)
    for y in range(8):
        for x in range(w):
            if y >= 3: img[y][x] = 3
    for _ in range(70):
        cx = rnd.uniform(0, w); cy = rnd.uniform(2.5, 8); r = rnd.uniform(1.6, 2.6); c = rnd.choice((1, 2, 1))
        for y in range(8):
            for x in range(w):
                d = (x+.5-cx)**2 + (y+.5-cy)**2
                if d <= r*r: img[y][x] = c
                elif d <= (r+.8)**2 and img[y][x] == 0: img[y][x] = 3
    return img

def rays_img():
    img = blank(160, 96)  # screen rows 3..14
    cx, cy = 80, 48
    for y in range(96):
        for x in range(160):
            a = math.atan2(y + .5 - cy, x + .5 - cx)
            w = int(math.floor((a + math.pi) / (2 * math.pi) * 12 + 0.5)) % 12
            img[y][x] = 1 + (w % 3)
    return img


