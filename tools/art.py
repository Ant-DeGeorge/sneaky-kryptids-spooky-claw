    on = set()
    for y, row in enumerate(g):
        for x, c in enumerate(row):
            if c == '#': on.add((x, y)); on.add((x + 1, y))   # bold horizontally
    for (x, y) in on:
        if (x + 1, y + 1) not in on and x + 1 < 8 and y + 1 < 8: t[y+1][x+1] = 1
