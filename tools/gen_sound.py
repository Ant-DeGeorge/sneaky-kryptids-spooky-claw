#!/usr/bin/env python3
"""Music data generator for Spooky Claw.

Songs are written as note-name strings and compiled to (note, frames) byte
pairs.  Note byte 0 = rest, 0xFF = end of track.

Main theme: "In the Hall of the Mountain King" (Edvard Grieg, 1875 - public
domain), arranged in A minor.
"""
import os, re

OUT = os.path.join(os.path.dirname(__file__), "..", "src", "sound_data.c")
NAMES = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B']
LOW_OCT, HIGH_OCT = 1, 7

def note_index(n):  # 1-based index from C1
    m = re.fullmatch(r"([A-G]#?)(\d)", n)
    return NAMES.index(m.group(1)) + (int(m.group(2)) - LOW_OCT) * 12 + 1

def freq(i):
    semis_from_a4 = (i - 1) + LOW_OCT * 12 - (4 * 12 + 9)
    return 440.0 * 2 ** (semis_from_a4 / 12)

N_NOTES = (HIGH_OCT - LOW_OCT + 1) * 12
sq = [0] + [max(0, min(2047, round(2048 - 131072 / freq(i)))) for i in range(1, N_NOTES + 1)]
wv = [0] + [max(0, min(2047, round(2048 - 65536 / freq(i)))) for i in range(1, N_NOTES + 1)]

def track(s, tick):
    out = []
    for tok in s.split():
        if ':' in tok: n, d = tok.split(':'); d = int(d)
        else: n, d = tok, 1
        out += [0 if n == 'R' else note_index(n), d * tick]
    return out

def pizz(s, tick):
    """Bass: every note becomes a one-tick pluck followed by a one-tick rest."""
    out = []
    for tok in s.split():
        out += [note_index(tok), tick, 0, tick]
    return out

# ----------------------------------------------------------------- main theme
T = 9  # frames per eighth note
A1 = "A3 B3 C4 D4 E4 C4 E4:2  D#4 B3 D#4:2 D4 A#3 D4:2  A3 B3 C4 D4 E4 C4 E4 A4  G4 E4 C4 E4 G4:4"
A2 = "A3 B3 C4 D4 E4 C4 E4:2  D#4 B3 D#4:2 D4 A#3 D4:2  A3 B3 C4 D4 E4 C4 E4 A4  G4 E4 C4 E4 A4:4"
B1 = "E4 F#4 G#4 A4 B4 G#4 B4:2  C5 G#4 C5:2 B4 G#4 B4:2  E4 F#4 G#4 A4 B4 G#4 B4 E5  D5 B4 G#4 B4 D5:4"
melody = track(A1 + " " + A2 + " " + B1 + " " + A2, T)
BA = "A2 E2 A2 E2  B2 F#2 A#2 F2  A2 E2 A2 E2  E2 B2 E2 E2"
BB = "E2 B2 E2 B2  C3 G#2 B2 G#2  E2 B2 E2 B2  B2 F#2 B2 E2"
bass = pizz(BA + " " + BA + " " + BB + " " + BA, T)

# ----------------------------------------------------------------- fanfares
F = 6
fan_mel = track("G4 C5 E5 G5:2 E5 G5:5 R:2", F)
fan_bas = pizz("C3 G2 C3 E3 C3", F)
PT = 7
party_mel = track("C5 E5 G5 C6:2 G5 C6:4  A4 C5 F5 A5:2 F5 A5:4  G4 B4 D5 G5:2 D5 G5:2 B5:2  C6:2 G5:2 E5:2 C6:6 R:2", PT)
party_bas = pizz("C3 G2 C3 G2  F2 C3 F2 C3  G2 D3 G2 D3  C3 G2 E2 C3", PT)
title_jingle = track("E5 G5 C6:3 R:1", 5)
LT = 14
lose_mel = track("G4:2 F#4:2 F4:2 E4:7 R:2", LT // 2 * 2)
lose_bas = pizz("C3 B2 A#2 A2", LT)
clear_mel = track("C5 E5 G5 C6:2 R:1 G5 C6:3 R:1", 6)
clear_bas = pizz("C3 G2 C3 E3 G3 C3", 6)
ET = 8
end_mel = track("E5:2 G5:2 C6:2 B5 A5 G5:4 R:1 A5:2 B5:2 C6:3 D6 E6:5 R:2  C6 E6 G6:3 E6 C6 G5:4 R:1 A5 C6 E6:3 C6 A5 G5:6 R:2", ET)
end_bas = pizz("C3 G2 C3 G2 F2 C3 F2 C3 G2 D3 G2 D3 C3 G2 E2 C3 A2 E2 A2 E2 F2 C3 F2 C3 G2 D3 G2 D3 C3 G2 C3 C3", ET)

def c_arr(name, data, loop):
    data = data + [0xFF, 1 if loop else 0]
    s = f"const uint8_t {name}[{len(data)}] = {{\n"
    for i in range(0, len(data), 16):
        s += "  " + ",".join(str(b) for b in data[i:i+16]) + ",\n"
    return s + "};\n"

src = ["// AUTO-GENERATED by tools/gen_sound.py", "#include <stdint.h>", ""]
src.append(f"const uint16_t sq_freq[{len(sq)}] = {{" + ",".join(map(str, sq)) + "};")
src.append(f"const uint16_t wave_freq[{len(wv)}] = {{" + ",".join(map(str, wv)) + "};")
src.append(c_arr("mus_theme_mel", melody, True))
src.append(c_arr("mus_theme_bass", bass, True))
src.append(c_arr("mus_fanfare_mel", fan_mel, False))
src.append(c_arr("mus_fanfare_bass", fan_bas, False))
src.append(c_arr("mus_party_mel", party_mel, False))
src.append(c_arr("mus_party_bass", party_bas, False))
src.append(c_arr("mus_lose_mel", lose_mel, False))
src.append(c_arr("mus_lose_bass", lose_bas, False))
src.append(c_arr("mus_clear_mel", clear_mel, False))
src.append(c_arr("mus_clear_bass", clear_bas, False))
src.append(c_arr("mus_end_mel", end_mel, True))
src.append(c_arr("mus_end_bass", end_bas, True))
open(OUT, "w").write("\n".join(src))
print("theme length (frames):", sum(melody[1::2]), "bass:", sum(bass[1::2]))
